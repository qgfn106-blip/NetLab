#!/usr/bin/env python3
"""从 docs/canonical/contracts 生成 TS/Python 契约产物。

唯一真源：
  docs/canonical/contracts/schemas/*.schema.json
  docs/canonical/contracts/compatibility.yaml
  docs/canonical/contracts/plot_semantics.yaml

生成物：
  frontend/app/contracts.ts
  netlab/contracts/generated.py

用法：python tools/gen_contracts.py [--check]
--check 只比较，不写盘；有漂移 exit 1。
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
CANON = ROOT / "docs" / "canonical" / "contracts"
SCHEMAS = CANON / "schemas"
TS_OUT = ROOT / "frontend" / "app" / "contracts.ts"
PY_OUT = ROOT / "netlab" / "contracts" / "generated.py"

TYPE_NAMES = {
    "channel_key": "ChannelKey",
    "frame": "Frame",
    "project": "ProjectV6",
    "plot_spec": "PlotSpec",
}


def load_schemas() -> dict[str, dict[str, Any]]:
    result: dict[str, dict[str, Any]] = {}
    for path in sorted(SCHEMAS.glob("*.schema.json")):
        name = path.name.split(".schema.json")[0]
        result[name] = json.loads(path.read_text(encoding="utf-8"))
    return result


def load_compat() -> dict[str, Any]:
    import yaml

    return yaml.safe_load((CANON / "compatibility.yaml").read_text(encoding="utf-8"))


def load_plot_semantics() -> dict[str, Any]:
    import yaml

    return yaml.safe_load((CANON / "plot_semantics.yaml").read_text(encoding="utf-8"))


def ts_type(prop: dict[str, Any]) -> str:
    if "const" in prop:
        value = prop["const"]
        return json.dumps(value, ensure_ascii=False) if isinstance(value, str) else str(value).lower()
    if "enum" in prop:
        return " | ".join(
            json.dumps(v, ensure_ascii=False) if isinstance(v, str) else str(v).lower()
            for v in prop["enum"]
        )
    kind = prop.get("type")
    if kind == "string":
        return "string"
    if kind in ("number", "integer"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "object":
        extra = prop.get("additionalProperties")
        if isinstance(extra, dict):
            return "Record<string, " + ts_type(extra) + ">"
        return "Record<string, unknown>"
    if kind == "array":
        item = prop.get("items") or {}
        return "Array<" + ts_type(item) + ">"
    return "unknown"


def render_ts(
    schemas: dict[str, dict[str, Any]],
    compat: dict[str, Any],
    plot_semantics: dict[str, Any],
) -> str:
    lines = [
        "// AUTO-GENERATED by tools/gen_contracts.py from docs/canonical/contracts — do not edit.",
        "/* eslint-disable */",
        "",
    ]
    for name, schema in schemas.items():
        type_name = TYPE_NAMES.get(name, "".join(p.title() for p in name.split("_")))
        lines.append(f"export interface {type_name} {{")
        required = set(schema.get("required", []))
        for prop_name, prop in schema.get("properties", {}).items():
            optional = "" if prop_name in required else "?"
            lines.append(f"  {prop_name}{optional}: {ts_type(prop)};")
        lines.append("}")
        lines.append("")
    versions = compat.get("schemas", {})
    lines.append("export const CONTRACT_VERSIONS = {")
    for name, version in versions.items():
        value = json.dumps(version, ensure_ascii=False)
        lines.append(f"  {name}: {value},")
    lines.append("} as const;")
    lines.append("")
    lines.append(f'export const PLOTKIT_API_VERSION = "{compat.get("api_version", "1")}";')
    lines.append("")
    lines.append("export const PLOT_SEMANTICS = {")
    mapping = (
        ("time_field", "timeField"),
        ("value_field", "valueField"),
        ("line_width", "lineWidth"),
        ("grid_width", "gridWidth"),
        ("max_points", "maxPoints"),
        ("sync_pull_limit", "syncPullLimit"),
        ("max_channels", "maxChannels"),
        ("downsample", "downsample"),
    )
    for src, dst in mapping:
        value = plot_semantics[src]
        lines.append(f"  {dst}: {json.dumps(value, ensure_ascii=False)},")
    lines.append("} as const;")
    return "\n".join(lines) + "\n"


def version_tuple(text: str) -> tuple[int, ...]:
    return tuple(int(part) for part in text.split(".") if part.isdigit())


def render_py(compat: dict[str, Any], plot_semantics: dict[str, Any]) -> str:
    plotkit = compat.get("plotkit", {})
    minimum = version_tuple(str(plotkit.get("min", "0.2.0")))
    maximum = version_tuple(str(plotkit.get("max_exclusive", "0.3.0")))
    return (
        '"""AUTO-GENERATED by tools/gen_contracts.py — do not edit."""\n'
        "from __future__ import annotations\n\n"
        f'API_VERSION = "{compat.get("api_version", "1")}"\n'
        f"PLOTKIT_MIN = {minimum!r}\n"
        f"PLOTKIT_MAX_EXCLUSIVE = {maximum!r}\n"
        f"SCHEMA_VERSIONS = {json.dumps(compat.get('schemas', {}), ensure_ascii=False, sort_keys=True)}\n"
        "\n"
        f"PLOT_TIME_FIELD = {plot_semantics['time_field']!r}\n"
        f"PLOT_VALUE_FIELD = {plot_semantics['value_field']!r}\n"
        f"PLOT_LINE_WIDTH = {plot_semantics['line_width']!r}\n"
        f"PLOT_GRID_WIDTH = {plot_semantics['grid_width']!r}\n"
        f"PLOT_MAX_POINTS = {plot_semantics['max_points']!r}\n"
        f"PLOT_SYNC_PULL_LIMIT = {plot_semantics['sync_pull_limit']!r}\n"
        f"PLOT_MAX_CHANNELS = {plot_semantics['max_channels']!r}\n"
        f"PLOT_DOWNSAMPLE = {plot_semantics['downsample']!r}\n"
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    schemas = load_schemas()
    compat = load_compat()
    plot_semantics = load_plot_semantics()
    ts = render_ts(schemas, compat, plot_semantics)
    py = render_py(compat, plot_semantics)

    drift: list[str] = []
    for path, content in ((TS_OUT, ts), (PY_OUT, py)):
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                drift.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")

    if args.check and drift:
        print("contract drift: " + ", ".join(drift))
        print("run: python tools/gen_contracts.py")
        return 1
    print(f"OK: {len(schemas)} schemas, {len(compat.get('schemas', {}))} versions")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
