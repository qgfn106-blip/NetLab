// frontend/scripts/gen_theme_css.mjs
// 构建期：从 theme.tokens.ts 的 LIGHT / DARK 生成 frontend/theme.generated.css。
// 运行时零构建：本脚本只在开发/构建时跑一次，产物 theme.generated.css 入库。
// 无第三方依赖；LIGHT / DARK 为纯数据对象，用括号匹配 + eval 读取（不做 TypeScript 转译）。
//
// 用法：node frontend/scripts/gen_theme_css.mjs   （在 NetlabHome 下或 scripts 目录均可）

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const srcPath = path.resolve(here, '..', 'theme.tokens.ts');
const outPath = path.resolve(here, '..', 'theme.generated.css');

const src = fs.readFileSync(srcPath, 'utf8');

// 从 `export const NAME ... = { ... }` 中取出对象字面量并求值（纯字符串键值，安全）。
function readObject(name) {
  const marker = `export const ${name}`;
  const at = src.indexOf(marker);
  if (at < 0) throw new Error(`theme.tokens.ts 中未找到 ${marker}`);
  const braceStart = src.indexOf('{', at);
  if (braceStart < 0) throw new Error(`${name} 缺少对象字面量`);
  let depth = 0;
  let inStr = null;
  let esc = false;
  let end = -1;
  for (let i = braceStart; i < src.length; i++) {
    const ch = src[i];
    if (inStr) {
      if (esc) { esc = false; continue; }
      if (ch === '\\') { esc = true; continue; }
      if (ch === inStr) inStr = null;
      continue;
    }
    if (ch === '"' || ch === "'" || ch === '`') { inStr = ch; continue; }
    if (ch === '{') depth++;
    else if (ch === '}') {
      depth--;
      if (depth === 0) { end = i; break; }
    }
  }
  if (end < 0) throw new Error(`${name} 对象字面量未闭合`);
  const literal = src.slice(braceStart, end + 1);
  // 纯数据对象，直接求值。
  // eslint-disable-next-line no-new-func
  return new Function('return (' + literal + ');')();
}

function block(selector, extraDecl, map) {
  const parts = [];
  if (extraDecl) parts.push(extraDecl);
  for (const [k, v] of Object.entries(map)) parts.push(`--${k}:${v}`);
  return `${selector}{${parts.join(';')};}`;
}

const LIGHT = readObject('LIGHT');
const DARK = readObject('DARK');

const out =
  '/* AUTO-GENERATED by frontend/scripts/gen_theme_css.mjs — DO NOT EDIT BY HAND.\n' +
  ' * 唯一来源：frontend/theme.tokens.ts（LIGHT / DARK）。改色请改 theme.tokens.ts 后重跑生成脚本。\n' +
  ' * 加载顺序：必须在 frontend/style.css 之前（见 frontend/index.html）。\n' +
  ' */\n' +
  block(':root', 'color-scheme:light', LIGHT) + '\n' +
  block('html[data-theme="dark"]', 'color-scheme:dark', DARK) + '\n';

fs.writeFileSync(outPath, out, 'utf8');
console.log(`wrote theme.generated.css  (:root ${Object.keys(LIGHT).length} vars, dark ${Object.keys(DARK).length} vars)`);
